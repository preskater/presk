function localize(value: unknown): unknown {
  if (typeof value === "string") {
    return seedTranslations[value] ?? value
  }
  if (Array.isArray(value)) {
    return value.map((item) => localize(item))
  }
  if (value instanceof Date) {
    return value
  }
  if (value && typeof value === "object") {
    const result: Record<string, unknown> = {}
    for (const [key, item] of Object.entries(value as Record<string, unknown>)) {
      result[key] = localize(item)
    }
    return result
  }
  return value
}

export function localizeSeed<T>(value: T, locale: string): T {
  if (locale !== "fr") {
    return value
  }
  return localize(value) as T
}
